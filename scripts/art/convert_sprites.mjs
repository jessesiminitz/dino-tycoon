import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { assertAttachedSilhouette } from './silhouette.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const manifest = JSON.parse(readFileSync(`${root}assets-source/export-manifest.json`, 'utf8'));
const data = {};
const palettes = {};
const contacts = {};
const environment = {};
const terrain = {};
for (const [asset, spec] of Object.entries(manifest.assets)) {
  const frames = spec.frames.map((_, frame) => {
    const result = JSON.parse(readFileSync(`${root}assets-source/renders/${asset}-${frame}.json`, 'utf8'));
    if (result.asset !== asset || result.frame !== frame || result.rows.length !== spec.height ||
        result.rows.some((row) => row.length !== spec.width || /[^.BDFAGWEM]/.test(row))) {
      throw new Error(`Invalid exported frame ${asset}:${frame}`);
    }
    const hash = createHash('sha256').update(result.rows.join('\n')).digest('hex');
    if (hash !== result.hash) throw new Error(`Hash mismatch ${asset}:${frame}`);
    if (spec.grounded && !/[^.]/.test(result.rows.at(-1))) throw new Error(`Floating feet ${asset}:${frame}`);
    if (spec.kind === 'dino' && !result.rows.some((row) => row.includes('E'))) throw new Error(`Missing eye ${asset}:${frame}`);
    if (spec.kind === 'dino') assertAttachedSilhouette(result.rows, `${asset}:pose:${frame}`);
    if (spec.kind === 'terrain' && result.rows.some(row => row.includes('.'))) throw new Error(`Incomplete tile ${asset}:${frame}`);
    if (spec.kind === 'environment' && (/[BDFAGWEM]/.test(result.rows[0]+result.rows.at(-1)) || result.rows.some(row => row[0] !== '.' || row.at(-1) !== '.'))) throw new Error(`Clipped scenery ${asset}:${frame}`);
    if (result.contact) (contacts[asset] ??= []).push(result.contact);
    return result.rows;
  });
  if (frames.length > 1 && new Set(frames.map((f) => f.join('\n'))).size !== frames.length) {
    throw new Error(`Duplicate animation frames: ${asset}`);
  }
  const sprite = { width: spec.width, height: spec.height, frames };
  if (spec.modelOffsetX) sprite.modelOffsetX = spec.modelOffsetX;
  if (spec.kind === 'environment') environment[asset] = { ...sprite, colors: spec.colors, shadow: spec.shadow };
  else if (spec.kind === 'terrain') terrain[asset.slice(5)] = { ...sprite, colors: spec.colors };
  else data[asset] = sprite;
  if (spec.kind === 'building') palettes[asset] = spec.colors;
}
const target = `${root}src/render/generated`;
mkdirSync(target, { recursive: true });
const source = '// Generated by scripts/art/convert_sprites.mjs; edit Blender sources or cleanup patches.\n' +
  `export const BLENDER_ART = ${JSON.stringify(data, null, 2)} as const;\n` +
  `export const BLENDER_BUILDING_COLORS: Record<string, Record<string, string>> = ${JSON.stringify(palettes, null, 2)};\n`;
const path = `${target}/blenderArt.ts`;
const environmentPath = `${target}/blenderEnvironment.ts`;
const environmentSource = '// Generated by scripts/art/convert_sprites.mjs; edit Blender sources or cleanup patches.\n' +
  `export const BLENDER_ENVIRONMENT = ${JSON.stringify(environment, null, 2)} as const;\n` +
  `export const BLENDER_TERRAIN = ${JSON.stringify(terrain, null, 2)} as const;\n`;
const contactPath = `${root}assets-source/walk-contacts.json`;
const contactSource = JSON.stringify(contacts, null, 2) + '\n';
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== source) throw new Error('Generated art is stale; run npm run art:convert');
  if (readFileSync(environmentPath, 'utf8') !== environmentSource) throw new Error('Environment art is stale');
  if (readFileSync(contactPath, 'utf8') !== contactSource) throw new Error('Walk contacts are stale');
  console.log('Generated art matches all exported frame hashes.');
} else {
  writeFileSync(path, source);
  writeFileSync(environmentPath, environmentSource);
  writeFileSync(contactPath, contactSource);
  console.log(`Generated ${Object.keys(manifest.assets).join(', ')}.`);
}
