import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = fileURLToPath(new URL('../../', import.meta.url));
const manifest = JSON.parse(readFileSync(`${root}assets-source/export-manifest.json`, 'utf8'));
const data = {};
for (const [asset, spec] of Object.entries(manifest.assets)) {
  const frames = spec.frames.map((_, frame) => {
    const result = JSON.parse(readFileSync(`${root}assets-source/renders/${asset}-${frame}.json`, 'utf8'));
    if (result.asset !== asset || result.frame !== frame || result.rows.length !== spec.height ||
        result.rows.some((row) => row.length !== spec.width || /[^.BDFAGWEM]/.test(row))) {
      throw new Error(`Invalid exported frame ${asset}:${frame}`);
    }
    const hash = createHash('sha256').update(result.rows.join('\n')).digest('hex');
    if (hash !== result.hash) throw new Error(`Hash mismatch ${asset}:${frame}`);
    if (spec.grounded && !/[^.]/.test(result.rows.at(-1))) throw new Error(`Floating feet ${asset}:${frame}`);
    if (spec.kind === 'dino' && !result.rows.some((row) => row.includes('E'))) throw new Error(`Missing eye ${asset}:${frame}`);
    return result.rows;
  });
  if (frames.length > 1 && new Set(frames.map((f) => f.join('\n'))).size !== frames.length) {
    throw new Error(`Duplicate animation frames: ${asset}`);
  }
  data[asset] = { width: spec.width, height: spec.height, frames };
}
const target = `${root}src/render/generated`;
mkdirSync(target, { recursive: true });
const source = '// Generated by scripts/art/convert_sprites.mjs; edit Blender sources or cleanup patches.\n' +
  `export const BLENDER_ART = ${JSON.stringify(data, null, 2)} as const;\n` +
  `export const BLENDER_BUILDING_COLORS: Record<string, string> = ${JSON.stringify(manifest.buildingColors, null, 2)};\n`;
const path = `${target}/blenderArt.ts`;
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== source) throw new Error('Generated art is stale; run npm run art:convert');
  console.log('Generated art matches all exported frame hashes.');
} else {
  writeFileSync(path, source);
  console.log(`Generated ${Object.keys(data).join(', ')}.`);
}
