import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const manifest = JSON.parse(readFileSync(`${root}assets-source/export-manifest.json`,'utf8'));
const species = Object.keys(manifest.assets).filter(id => manifest.assets[id].kind === 'dino');
const clips = ['walk','idle','eat','rest'];
const data = {};
for (const asset of species) {
  data[asset] = {};
  for (const clip of clips) {
    const p = JSON.parse(readFileSync(`${root}assets-source/renders/motion/${asset}-${clip}.json`, 'utf8'));
    if (p.asset !== asset || p.clip !== clip || p.frames.length !== 8 || p.contacts.length !== 8 || p.durationMs <= 0) throw new Error(`Invalid clip ${asset}:${clip}`);
    p.frames.forEach((rows, i) => {
      const hash = createHash('sha256').update(rows.join('\n')).digest('hex');
      if (rows.length !== p.height || rows.some(row => row.length !== p.width || /[^.BDFAGWEM]/.test(row)) || hash !== p.hashes[i]) throw new Error(`Invalid frame ${asset}:${clip}:${i}`);
      if (!rows.some(row => row.includes('E')) || (manifest.assets[asset].grounded && !/[^.]/.test(rows.at(-1)))) throw new Error(`Missing face or planted feet ${asset}:${clip}:${i}`);
      if (manifest.assets[asset].grounded && !p.contacts[i].some(foot => foot.planted)) throw new Error(`No mesh ground contact ${asset}:${clip}:${i}`);
    });
    if (new Set(p.hashes).size < 3) throw new Error(`Insufficient motion ${asset}:${clip}`);
    data[asset][clip] = { width:p.width, height:p.height, durationMs:p.durationMs, frames:p.frames, contacts:p.contacts };
  }
}
const path = `${root}src/render/generated/blenderMotion.ts`;
// Shared rows reduce the download and avoid a giant inferred literal type.
const rows=[], rowIds=new Map();
for (const animal of Object.values(data)) for (const clip of Object.values(animal)) {
  clip.frames=clip.frames.map(frame=>frame.map(row=>{
    if (!rowIds.has(row)) { rowIds.set(row,rows.length); rows.push(row); }
    return rowIds.get(row);
  }));
}
const source = '// Generated by scripts/art/convert_motion.mjs from Blender animation timelines.\n' +
  `import type { SpeciesId } from '../../sim/data/species';\n` +
  `export type BlenderClipName = 'walk' | 'idle' | 'eat' | 'rest';\n` +
  `export interface BlenderMotionClip { width:number; height:number; durationMs:number; frames:readonly (readonly string[])[]; contacts:readonly (readonly {name:string;x:number;y:number;planted:boolean}[])[] }\n` +
  `const rows: string[] = ${JSON.stringify(rows)};\n` +
  `const packed = ${JSON.stringify(data)};\n` +
  `export const BLENDER_MOTION = Object.fromEntries(Object.entries(packed).map(([id,clips])=>[id,Object.fromEntries(Object.entries(clips).map(([name,clip])=>[name,{...clip,frames:clip.frames.map(frame=>frame.map(index=>rows[index]))}]))])) as unknown as Record<SpeciesId,Record<BlenderClipName,BlenderMotionClip>>;\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(path,'utf8') !== source) throw new Error('Full roster motion data is stale');
} else writeFileSync(path,source);
console.log(`Validated ${species.length} dinosaurs × 4 clips × 8 Blender frames, hashes and habitat contacts; ${rows.length} shared rows.`);
