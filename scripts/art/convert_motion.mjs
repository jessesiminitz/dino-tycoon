import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const species = ['carnotaurus','diplodocus','yutyrannus'];
const clips = ['walk','idle','eat','rest'];
const data = {};
for (const asset of species) {
  data[asset] = {};
  for (const clip of clips) {
    const p = JSON.parse(readFileSync(`${root}assets-source/renders/motion/${asset}-${clip}.json`, 'utf8'));
    if (p.asset !== asset || p.clip !== clip || p.frames.length !== 8 || p.contacts.length !== 8 || p.durationMs <= 0) throw new Error(`Invalid clip ${asset}:${clip}`);
    p.frames.forEach((rows, i) => {
      const hash = createHash('sha256').update(rows.join('\n')).digest('hex');
      if (rows.length !== p.height || rows.some(row => row.length !== p.width || /[^.BDFAGWEM]/.test(row)) || hash !== p.hashes[i]) throw new Error(`Invalid frame ${asset}:${clip}:${i}`);
      if (!rows.some(row => row.includes('E')) || !/[^.]/.test(rows.at(-1))) throw new Error(`Missing face or planted feet ${asset}:${clip}:${i}`);
      if (!p.contacts[i].some(foot => foot.planted)) throw new Error(`No mesh ground contact ${asset}:${clip}:${i}`);
    });
    if (new Set(p.hashes).size < 3) throw new Error(`Insufficient motion ${asset}:${clip}`);
    data[asset][clip] = { width:p.width, height:p.height, durationMs:p.durationMs, frames:p.frames, contacts:p.contacts };
  }
}
const path = `${root}src/render/generated/blenderMotion.ts`;
const source = '// Generated by scripts/art/convert_motion.mjs from Blender animation timelines.\n' +
  `export const BLENDER_MOTION = ${JSON.stringify(data, null, 2)} as const;\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(path,'utf8') !== source) throw new Error('Prototype motion data is stale');
} else writeFileSync(path,source);
console.log('Validated 3 dinosaurs × 4 clips × 8 Blender frames, hashes and ground contacts.');
