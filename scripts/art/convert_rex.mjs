// The park's hand-drawn T-rex: reads the frame strips pxl draws from assets-source/pxl/dinos/tyrannosaurus.px.js
// (`pxl build dinos/tyrannosaurus.px.js --only game_adult_walk,...`) and stores them as palette rows in
// src/render/generated/rexArt.ts. `--check` fails when the checked-in module is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const strips = `${root}assets-source/pxl/dinos/out/anims/`;
const CLIPS = ['walk', 'idle', 'eat', 'rest', 'roar', 'stomp', 'dance', 'hop', 'sneeze'];
const KEYS = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
const palette = new Map();

function frames(name) {
  const meta = JSON.parse(readFileSync(`${strips}${name}.json`, 'utf8'));
  const list = Object.values(meta.frames).map((f) => f.frame);
  const { w, h } = list[0];
  const width = list.length * w;
  const raw = execFileSync('magick', [`${strips}${name}.png`, '-depth', '8', 'rgba:-'], { maxBuffer: 1 << 26 });
  if (raw.length !== width * h * 4) throw new Error(`Unexpected strip size ${name}`);
  return list.map((f) => {
    const rows = [];
    for (let y = 0; y < h; y++) {
      let row = '';
      for (let x = f.x; x < f.x + w; x++) {
        const i = (y * width + x) * 4;
        if (raw[i + 3] < 128) { row += '.'; continue; }
        const hex = '#' + [raw[i], raw[i + 1], raw[i + 2]].map((v) => v.toString(16).padStart(2, '0')).join('');
        if (!palette.has(hex)) {
          if (palette.size >= KEYS.length) throw new Error('Too many T-rex colours');
          palette.set(hex, KEYS[palette.size]);
        }
        row += palette.get(hex);
      }
      rows.push(row);
    }
    if (!rows.at(-1).includes('.') && !/[^.]/.test(rows.at(-1))) throw new Error(`Empty frame ${name}`);
    return rows;
  });
}

const data = {};
for (const size of ['adult', 'baby']) {
  data[size] = { still: frames(`game_${size}_still`)[0], clips: {} };
  for (const clip of CLIPS) {
    const list = frames(`game_${size}_${clip}`);
    if (list.length !== 8) throw new Error(`game_${size}_${clip} needs eight frames`);
    data[size].clips[clip] = list;
  }
}
// Feet on the walk (rex2's gait in tyrannosaurus.px.js): a foot is planted for the first two thirds of its
// cycle while its stride slides from +0.6 to -0.6; x is the toe in adult canvas pixels (60 + stride * 11,
// the far leg 3 px back and half a cycle behind).
const SCALE = 0.713, PAD = 1, STRIDE = 0.6;
const gait = (phase) => { phase %= 1; return phase < 2 / 3 ? [STRIDE * (1 - 3 * phase), true] : [STRIDE * (-1 + 2 * (phase - 2 / 3) * 3), false]; };
const contacts = [...Array(8)].map((_, i) => [['near_toes', i / 8, 0], ['far_toes', i / 8 + 0.5, -3]].map(([name, phase, dx]) => {
  const [st, planted] = gait(phase);
  return { name, x: Math.round(((60 + dx + st * 11) * SCALE + PAD) * 100) / 100, planted };
}));
const rows = [], ids = new Map();
const pack = (frame) => frame.map((row) => { if (!ids.has(row)) { ids.set(row, rows.length); rows.push(row); } return ids.get(row); });
const packed = Object.fromEntries(Object.entries(data).map(([size, d]) => [size, {
  still: pack(d.still), clips: Object.fromEntries(Object.entries(d.clips).map(([clip, list]) => [clip, list.map(pack)])),
}]));
const source = '// Generated by scripts/art/convert_rex.mjs from the hand-drawn T-rex (assets-source/pxl/dinos/tyrannosaurus.px.js).\n' +
  `export type RexClipName = ${CLIPS.map((c) => `'${c}'`).join(' | ')};\n` +
  `export interface RexSize { still: readonly string[]; clips: Record<RexClipName, readonly (readonly string[])[]> }\n` +
  `/** Each row character is a colour key. */\n` +
  `export const REX_PALETTE: Record<string, string> = ${JSON.stringify(Object.fromEntries([...palette].map(([hex, key]) => [key, hex])))};\n` +
  `/** Drawn at this fraction of the model; the walk's planted toes in adult canvas pixels. */\n` +
  `export const REX_SCALE = ${SCALE};\n` +
  `/** Ground covered by one walk cycle, in adult park pixels: a planted foot slides 2 × 0.6 × 11 model px in two thirds of it. */\n` +
  `export const REX_WALK_CYCLE = ${Math.round(STRIDE * 2 * 11 * 1.5 * SCALE * 1000) / 1000};\n` +
  `export const REX_WALK_CONTACTS: readonly (readonly {name:string;x:number;planted:boolean}[])[] = ${JSON.stringify(contacts)};\n` +
  `const rows: string[] = ${JSON.stringify(rows)};\n` +
  `const packed = ${JSON.stringify(packed)};\n` +
  `const unpack = (frame: number[]) => frame.map((index) => rows[index]);\n` +
  `export const REX_ART = Object.fromEntries(Object.entries(packed).map(([size, d]) => [size, { still: unpack(d.still), clips: Object.fromEntries(Object.entries(d.clips).map(([clip, list]) => [clip, list.map(unpack)])) }])) as unknown as Record<'adult' | 'baby', RexSize>;\n`;
const path = `${root}src/render/generated/rexArt.ts`;
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== source) throw new Error('Hand-drawn T-rex data is stale');
} else writeFileSync(path, source);
console.log(`T-rex: ${CLIPS.length} clips × 8 frames, adult and baby, ${palette.size} colours, ${rows.length} shared rows.`);
